from typing import List, Tuple
from langchain_core.tools import StructuredTool

from app.lib.supabase import supabase_admin


def create_get_help_tool() -> StructuredTool:
    """
    創建幫助工具，提供智能助理的功能說明和使用指南
    
    Args:
        user_id: 用戶ID
        chatbot_id: 聊天機器人ID
        
    Returns:
        幫助工具
    """
    
    def get_help(query: str = "") -> str:
        """
        提供智能助理目前所支援的功能與用法，回答使用者在使用上的問題
        
        Args:
            query: 使用者的具體問題，如果為空則提供完整功能說明
            
        Returns:
            功能說明和使用指南
        """
        
        print(f"查詢支援功能，使用者詢問：{query}")
        
        # 完整的幫助內容
        help_content = """
✅ **智能助理功能說明與使用指南**

我是一個智能助理，主要提供活動提醒與筆記管理功能：

## ⏰ **提醒功能**
- **新增活動提醒**：可以新增活動的標題、內容、開始時間和結束時間
- **修改活動提醒**：可以修改活動的標題、內容、開始時間和結束時間
- **搜尋活動提醒**：可以搜尋特定時間範圍內的活動提醒
- **刪除活動提醒**：可以刪除不需要的活動提醒
- **提醒範例**：
    - 「半小時後提醒我回家」
    - 「下午三點提醒我去看電影」
    - 「明天下午2點提醒我開會」
    - 「下禮拜三，上午十點提醒我接機」


## 📝 **筆記管理功能**
- **記錄筆記**：您可以說「幫我記錄筆記」或「記下這件事」，我會自動判斷內容並建立筆記
- **搜尋筆記**：可以搜尋筆記標題或內容，例如「搜尋關於會議的筆記」
- **修改筆記**：可以修改筆記的標題或內容，我會保留原有內容並進行更新
- **查看筆記**：可以查看單一筆記或所有筆記列表
- **刪除筆記**：可以刪除不需要的筆記（會先確認）
- **新增筆記範例**：
    - 「筆記 標題 備用鑰匙的位置 內容 放在客廳的櫃子裡」
    - 「筆記 標題 我不能吃的食物 內容 洋蔥、大蒜、韭菜」
    - 「記錄 標題 王小明的資料 內容 王小明，身高175公分，體重70公斤，出生於1990年1月1日」

如果您有特定的使用問題，請直接詢問，我會為您提供詳細的說明！
        """
        return f"""
✅ **針對您的問題：{query}**

我理解您想了解「{query}」的相關資訊。讓我為您提供詳細說明：

{help_content}

如果您需要更具體的說明或有其他問題，請告訴我，我會為您提供更精確的答案！
                """
        
        # 如果沒有具體問題，返回完整幫助內容
        return help_content
    
    # 使用 StructuredTool 封裝
    get_help_tool = StructuredTool.from_function(
        func=get_help,
        name="get_help",
        description="提供智能助理支援的功能與使用範例，回答使用者在使用上的問題。可以詢問活動提醒、 筆記管理、記帳等功能的使用方法。",
        return_direct=False
    )
    
    return get_help_tool

